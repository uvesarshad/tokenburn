export const GLYPH_W = 5;
export const GLYPH_H = 7;
const NARROW = new Set(['.', ',', ':', '!', "'", '|']);

export const glyphs = new Map();
for (const [ch, s] of Object.entries(RAW)) {
  const rows = s.split('/');
  if (rows.length !== 7 || rows.some((r) => r.length !== 5)) {
    throw new Error(`bad glyph ${ch}`);
  }
  glyphs.set(ch, rows);
}

/** Horizontal advance in unscaled pixels (includes 1px spacing). */
export function advance(ch) {
  if (ch === ' ') return 3;
  if (NARROW.has(ch)) return 3;
  return 6;
}

/** Column range [from, to) of ink to draw for a glyph (trims narrow punctuation). */
export function inkRange(ch) {
  if (NARROW.has(ch)) {
    const rows = glyphs.get(ch);
    let from = 5;
    let to = 0;
    for (const r of rows) {
      for (let i = 0; i < 5; i++) {
        if (r[i] === '#') {
          from = Math.min(from, i);
          to = Math.max(to, i + 1);
        }
      }
    }
    return [from, to];
  }
  return [0, 5];
}

export function measure(text, scale = 1) {
  let w = 0;
  for (const ch of String(text).toUpperCase()) w += advance(ch) * scale;
  return Math.max(0, w - scale); // drop trailing spacing
}
